const assert = require('node:assert');
process.env.DB_PATH = ':memory:';
const { responder, parseKg, horarioValido } = require('./agent');
const db = require('./db');
assert.strictEqual(parseKg('1.5 toneladas'), 1500);
assert.strictEqual(parseKg('1,200 kilos'), 1200);
assert.strictEqual(parseKg('media tonelada'), 500);
assert.strictEqual(parseKg('hola'), null);
assert(horarioValido('Lunes a sábado de 5am a 2pm'));
assert(!horarioValido('mañana'));
const say = (m) => responder('t1', m);
say('');
['Juan Pérez', 'B-24', 'Frutas', '5551234567', '800 kg', '60', 'Lunes a viernes de 5am a 2pm'].forEach(say);
const r = say('sí');
assert(r.completo);
const reg = db.porSemana(require('./agent').lunesDeSemana());
assert.strictEqual(reg.length, 1);
assert.strictEqual(reg[0].kg_desecho, 60);
assert.match(say('x').mensajes[0], /ya está guardado/);
console.log('OK');
